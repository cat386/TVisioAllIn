#include <tvision/tv.h>

#if !defined( __STRING_H )
#include <string.h>
#endif  // __STRING_H

/*------------------------------------------------------------------------*/
/*                                                                        */
/*  newStr                                                                */
/*                                                                        */
/* Аргумент: */
/*                                                                        */
/* s — входная строка. */
/*                                                                        */
/* Возвращает: */
/*                                                                        */
/* Если s содержит нулевой указатель, возвращает нулевой указатель. */
/* Иначе выделяет s.size() + 1 байтов с */
/* копией s и завершающим '\0', возвращая указатель */
/* на первый байт. */
/* Возвращённую строку можно освободить через delete[]. */
/*                                                                        */
/*------------------------------------------------------------------------*/

char *newStr( TStringView s ) noexcept
{
    if( s.data() == 0 )
        return 0;
    char *temp = new char[ s.size()+1 ];
    memcpy( temp, s.data(), s.size() );
    temp[s.size()] = EOS;
    return temp;
}
